export function buildFullCurriculumStructure(): CurriculumStructure {
  const enrichedModules: CurriculumModuleDefinition[] = CURRICULUM_MODULES.map((baseMod) => {
    const modId = baseMod.id;
    const prereqRelations = CANONICAL_PREREQUISITE_RELATIONS.filter(
      (rel) => rel.sourceModuleId === modId || rel.targetModuleId === modId
    );
    const labReqs = CANONICAL_LAB_REQUIREMENTS[modId] || [
      {
        id: `lab-req-${baseMod.number}-gen`,
        moduleId: modId,
        title: `${baseMod.title} Research Invariant Verification`,
        difficulty: baseMod.difficulty,
        targetSecurityInvariant: `System components must enforce ${baseMod.shortTitle} invariants across untrusted boundary inputs.`,
        primaryVulnerabilityClass: baseMod.track,
        controlledMutationsCount: 2,
        proofObligationDescription: `Formulate a testable hypothesis, record baseline response, mutate target parameter, and prove invariant failure.`,
        minimumConfidenceScore: 80,
        requiresFalsePositiveExclusion: true,
        expectedArtifactType: 'http-differential' as const,
      },
    ];

    const cveCases = CANONICAL_CVE_CASE_STUDIES[modId] || [];

    return {
      ...baseMod,
      prerequisiteRelations: prereqRelations,
      labRequirements: labReqs,
      cveCaseStudies: cveCases,
    };
  });

  return {
    version: '2026.1',
    lastSynchronizedAt: new Date().toISOString(),
    totalModules: enrichedModules.length,
    totalLessons: LESSONS_CATALOG.length,
    totalLabRequirements: enrichedModules.reduce(
      (sum, m) => sum + (m.labRequirements ? m.labRequirements.length : 0),
      0
    ),
    modules: enrichedModules,
    prerequisiteGraph: CANONICAL_PREREQUISITE_RELATIONS,
  };
}

